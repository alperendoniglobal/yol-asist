/** İl adından sabit listedeki anahtarı bul (büyük/küçük harf, İ/i duyarsız) */
export function getCityKey(cityName: string): string | null {
  const s = String(cityName || '').trim();
  if (!s) return null;
  const norm = (t: string) => t.replace(/İ/g, 'I').replace(/ı/g, 'i').toLowerCase();
  const keys = Object.keys(TURKISH_CITY_COORDINATES);
  const found = keys.find((k) => norm(k) === norm(s));
  return found ?? null;
}
